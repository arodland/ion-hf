fn rand_bits(rng: &mut design::Rng, n: usize) -> Vec<u8> {
    (0..n).map(|_| (rng.next_u64() >> 63) as u8).collect()
}

/// BPSK (bit 0 -> +1) over AWGN at `es_n0_db` per coded bit; returns the
/// calibrated channel LLRs `2 y / sigma^2`.
fn bpsk_awgn(bits: &[u8], es_n0_db: f64, noise: &mut NoiseGen) -> Vec<f32> {
    let sigma2 = 1.0 / (2.0 * 10f64.powf(es_n0_db / 10.0));
    let sigma = sigma2.sqrt() as f32;
    let scale = (2.0 / sigma2) as f32;
    bits.iter()
        .map(|&b| {
            let s = if b == 0 { 1.0 } else { -1.0 };
            (s + sigma * noise.gaussian()) * scale
        })
        .collect()
}

fn clean_llrs(bits: &[u8]) -> Vec<f32> {
    bits.iter().map(|&b| if b == 0 { 8.0 } else { -8.0 }).collect()
}

/// Es/N0 (dB per coded bit) at which the normal approximation gives 1%
/// FER, plus `margin`. Used as a "moderate" operating point in tests.
fn moderate_db(n: usize, k: usize, margin: f64) -> f64 {
    design::normal_approx_db(n, k, 0.01) + margin
}

