/// Seeds of the design. Changing any of these changes the code on the air.
const SEED_BASE: u64 = 0x4845_524D_4553_0001;
const SEED_Z90: u64 = 0x4845_524D_4553_107C;
const SEED_Z16: u64 = 0x4845_524D_4553_1040;
/// First seed of the lifting search in `generate_tables`.
const SEED_LIFT0: u64 = 0x4845_524D_4553_1000;
const EXT_ROWS: usize = 46;
const MAX_PAIR: usize = 10;
/// Most rows holding both punctured columns (see `design::design_base`).
const MAX_PUNCT_PAIR: usize = 6;

fn fmt_rows<T: std::fmt::Display>(name: &str, ty: &str, rows: &[Vec<T>]) -> String {
    let mut s = format!("pub(crate) const {name}: [&[{ty}]; MB] = [\n");
    for r in rows {
        let items: Vec<String> = r.iter().map(|v| v.to_string()).collect();
        s += &format!("    &[{}],\n", items.join(", "));
    }
    s += "];\n";
    s
}

/// Seeds tried per lifting by `generate_tables`; the chosen ones are
/// `SEED_Z90` / `SEED_Z16`.
const LIFT_TRIES: u64 = 256;

/// Regenerates `src/fec/tables.rs`: PEXIT-greedy protograph, then the two
/// liftings. Writes to `$ION_FEC_TABLES` (or prints to stdout). With
/// `ION_FEC_KEEP_BASE=1` the base matrix in use is kept and only the
/// lifting seeds are searched (from `SEED_LIFT0`).
/// Run: `cargo test -p ion --release --test fec generate_tables -- --ignored --nocapture`
#[test]
#[ignore]
fn generate_tables() {
    let t = std::time::Instant::now();
    let base = if std::env::var("ION_FEC_KEEP_BASE").is_ok() {
        design::table_base()
    } else {
        design::design_base(EXT_ROWS, SEED_BASE, MAX_PAIR, MAX_PUNCT_PAIR, true)
    };
    eprintln!("base designed in {:.1} s", t.elapsed().as_secs_f64());
    for z in [90, 16] {
        let sd = design::best_lift_seed(&base, z, SEED_LIFT0, LIFT_TRIES);
        eprintln!("Z={z}: best lifting seed {sd:#x}");
    }
    let s90 = design::lift(&base, 90, SEED_Z90);
    let s16 = design::lift(&base, 16, SEED_Z16);
    let mb = base.len();
    for (z, s) in [(90, &s90), (16, &s16)] {
        let (c4, c6, c8) = design::cycle_counts(&base, s, z, mb);
        let (c4c, c6c, c8c) = design::cycle_counts(&base, s, z, 4);
        eprintln!(
            "Z={z}: closed base cycles: 4-cycles {c4}, 6-cycles {c6}, 4-cycles at Z/2 {c8} (core only {c4c}/{c6c}/{c8c})"
        );
    }
    let base_u8: Vec<Vec<u8>> = base.iter().map(|r| r.iter().map(|&c| c as u8).collect()).collect();
    let mut out = String::new();
    out += "//! Ion LDPC tables. GENERATED by `tests/fec.rs::generate_tables`\n";
    out += "//! (PEXIT-greedy PBRL protograph and girth-aware liftings, see\n";
    out += "//! `docs/fec.md`). Do not edit by hand: these define the code\n";
    out += "//! on the air.\n";
    out += &format!(
        "//!\n//! Seeds: base {SEED_BASE:#x}, Z=90 {SEED_Z90:#x}, Z=16 {SEED_Z16:#x}; \
         max rows per column pair {MAX_PAIR}, with both punctured columns {MAX_PUNCT_PAIR}.\n\n"
    );
    out += "/// Information columns (columns `0..PUNCT` are never sent).\n";
    out += "pub(crate) const KB: usize = 16;\n";
    out += "pub(crate) const PUNCT: usize = 2;\n";
    out += "pub(crate) const CORE_ROWS: usize = 4;\n";
    out += &format!("pub(crate) const EXT_ROWS: usize = {EXT_ROWS};\n");
    out += "pub(crate) const MB: usize = CORE_ROWS + EXT_ROWS;\n\n";
    out += "/// Free (non-structural) columns of each base row. The parity part\n";
    out += "/// is added by `design::full_rows`.\n";
    out += &fmt_rows("BASE", "u8", &base_u8);
    out += "\n/// Circulant shifts of the `BASE` entries for `Z = 90`.\n";
    out += &fmt_rows("SHIFT_90", "u16", &s90);
    out += "\n/// Circulant shifts of the `BASE` entries for `Z = 16`.\n";
    out += &fmt_rows("SHIFT_16", "u16", &s16);
    match std::env::var("ION_FEC_TABLES") {
        Ok(p) => std::fs::write(p, out).unwrap(),
        Err(_) => println!("{out}"),
    }
}

/// PEXIT thresholds of the protograph in use, one line per extension row.
/// Run: `cargo test -p ion --release --test fec pexit_report -- --ignored --nocapture`
#[test]
#[ignore]
fn pexit_report() {
    let base = design::table_base();
    println!("| ext rows | rate | PEXIT threshold Es/N0 (dB) | Shannon limit (dB) | gap (dB) |");
    println!("|---:|---:|---:|---:|---:|");
    for e in 0..=EXT_ROWS {
        let r = design::proto_rate(e);
        let t = design::pexit_threshold(&base, e, 6.0, 2000);
        let l = design::bi_awgn_limit_db(r);
        println!("| {e} | {r:.3} | {t:.3} | {l:.3} | {:.3} |", t - l);
    }
}

#[test]
fn shannon_limit_sanity() {
    // BPSK rate 1/2: Eb/N0 limit about 0.19 dB, i.e. Es/N0 = Eb/N0 - 3.01 dB.
    let es = design::bi_awgn_limit_db(0.5);
    let eb = es + 10.0 * 2f64.log10();
    assert!((eb - 0.19).abs() < 0.03, "{eb}");
}

