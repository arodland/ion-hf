#[derive(Clone, Copy)]
enum Code {
    Main(Rate),
    Short,
    /// First `n` bits of the main transmission order (HARQ-style prefix).
    Prefix(usize),
}

impl Code {
    fn all() -> Vec<Code> {
        Rate::ALL.iter().map(|&r| Code::Main(r)).chain([Code::Short]).collect()
    }
    fn n(self) -> usize {
        match self {
            Code::Main(r) => r.n(),
            Code::Short => fec::n_short(),
            Code::Prefix(n) => n,
        }
    }
    fn k(self) -> usize {
        match self {
            Code::Main(_) | Code::Prefix(_) => fec::K,
            Code::Short => fec::K_SHORT,
        }
    }
    fn name(self) -> String {
        match self {
            Code::Main(r) => format!("{r:?}"),
            Code::Short => "short".into(),
            Code::Prefix(n) => format!("prefix {n}"),
        }
    }
    fn encode(self, info: &[u8]) -> Vec<u8> {
        match self {
            Code::Main(r) => fec::encode(r, info),
            Code::Short => fec::encode_short(info),
            Code::Prefix(n) => {
                let x = fec::encode_mother(info);
                fec::transmission_order()[..n].iter().map(|&p| x[p]).collect()
            }
        }
    }
    fn decode(self, d: &mut Decoder, llr: &[f32]) -> Option<Vec<u8>> {
        match self {
            Code::Main(r) => d.decode(r, llr),
            Code::Short => d.decode_short(llr),
            Code::Prefix(_) => d.decode_prefix(llr),
        }
    }
}

struct Point {
    db: f64,
    frames: usize,
    errors: usize,
    undetected: usize,
    iters: usize,
}

impl Point {
    fn fer(&self) -> f64 {
        self.errors as f64 / self.frames as f64
    }
}

fn env_or<T: std::str::FromStr>(name: &str, default: T) -> T {
    std::env::var(name).ok().and_then(|v| v.parse().ok()).unwrap_or(default)
}

/// Simulates `code` at `db` on all cores until `max_err` frame errors or
/// `max_frames` frames.
fn sim(code: Code, db: f64, algo: Algorithm, max_frames: usize, max_err: usize, seed: u64) -> Point {
    use std::sync::atomic::{AtomicUsize, Ordering::Relaxed};
    let frames = AtomicUsize::new(0);
    let errors = AtomicUsize::new(0);
    let undetected = AtomicUsize::new(0);
    let iters = AtomicUsize::new(0);
    let nt = std::thread::available_parallelism().map_or(4, |n| n.get());
    std::thread::scope(|s| {
        for t in 0..nt as u64 {
            let (frames, errors, undetected, iters) = (&frames, &errors, &undetected, &iters);
            s.spawn(move || {
                let mut rng = design::Rng::new(seed.wrapping_mul(0x9E37) ^ (t + 1));
                let mut noise = NoiseGen::new(seed.wrapping_mul(31) + t + 1);
                let mut dec = Decoder::new();
                dec.set_algorithm(algo);
                dec.set_max_iterations(env_or("ION_FEC_ITERS", Decoder::MAX_ITER));
                while frames.load(Relaxed) < max_frames && errors.load(Relaxed) < max_err {
                    let info = rand_bits(&mut rng, code.k());
                    let llr = bpsk_awgn(&code.encode(&info), db, &mut noise);
                    let out = code.decode(&mut dec, &llr);
                    iters.fetch_add(dec.iterations(), Relaxed);
                    frames.fetch_add(1, Relaxed);
                    match out {
                        Some(b) if b == info => {}
                        Some(_) => {
                            errors.fetch_add(1, Relaxed);
                            undetected.fetch_add(1, Relaxed);
                        }
                        None => {
                            errors.fetch_add(1, Relaxed);
                        }
                    }
                }
            });
        }
    });
    Point {
        db,
        frames: frames.into_inner(),
        errors: errors.into_inner(),
        undetected: undetected.into_inner(),
        iters: iters.into_inner(),
    }
}

/// Es/N0 at which the FER crosses `target`, interpolating log10(FER).
fn crossing(pts: &[Point], target: f64) -> Option<f64> {
    pts.windows(2).find_map(|w| {
        let (f0, f1) = (w[0].fer(), w[1].fer());
        (f0 >= target && f1 < target).then(|| {
            let (l0, l1) = (f0.log10(), f1.max(1e-6).log10());
            let t = (target.log10() - l0) / (l1 - l0);
            w[0].db + t * (w[1].db - w[0].db)
        })
    })
}

/// Sweeps `code` from below its normal-approximation 1% point until the
/// FER drops under 1e-3.
fn sweep(code: Code, algo: Algorithm, step: f64, max_frames: usize, seed: u64) -> Vec<Point> {
    let na = design::normal_approx_db(code.n(), code.k(), 0.01);
    let mut db = (na / step).floor() * step;
    let mut pts: Vec<Point> = Vec::new();
    loop {
        let p = sim(code, db, algo, max_frames, 200, seed + pts.len() as u64);
        eprintln!(
            "{} {algo:?} {db:.2} dB: {}/{} FER {:.2e}",
            code.name(),
            p.errors,
            p.frames,
            p.fer()
        );
        let fer = p.fer();
        pts.push(p);
        if fer < 1e-3 || pts.len() > 40 {
            return pts;
        }
        db += step;
    }
}

/// 1% FER thresholds of sum-product and of normalized min-sum with
/// several factors (to pick `Decoder::ALGORITHM`).
/// Run: `cargo test -p ion --release --test fec algorithm_sweep -- --ignored --nocapture`
#[test]
#[ignore]
fn algorithm_sweep() {
    let frames = env_or("ION_FEC_FRAMES", 5000);
    let algos = [
        Algorithm::SumProduct,
        Algorithm::MinSum(0.7),
        Algorithm::MinSum(0.8),
        Algorithm::MinSum(0.9),
        Algorithm::MinSum(1.0),
    ];
    for code in Code::all() {
        for algo in algos {
            let pts = sweep(code, algo, 0.2, frames, 77);
            match crossing(&pts, 0.01) {
                Some(t) => println!("RESULT {} {algo:?}: 1% at {t:.2} dB", code.name()),
                None => println!("RESULT {} {algo:?}: no crossing", code.name()),
            }
        }
    }
}

/// FER vs Es/N0 for every rate and the short code; writes markdown to
/// `$ION_FEC_RESULTS` (or stdout).
/// Run: `cargo test -p ion --release --test fec fer_tables -- --ignored --nocapture`
#[test]
#[ignore]
fn fer_tables() {
    let max_frames = env_or("ION_FEC_FRAMES", 20_000);
    let step = env_or("ION_FEC_STEP", 0.25);
    let q = 10.0 * 2f64.log10();
    let mut out = String::new();
    let mut summary = String::from(
        "| code | n | k | 1% FER Es/N0 BPSK (dB) | Eb/N0 (dB) | Es/N0 QPSK (dB) \
         | normal approx. (dB) | gap to NA (dB) | Shannon limit (dB) | gap to Shannon (dB) |\n\
         |---|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n",
    );
    let only = std::env::var("ION_FEC_ONLY").unwrap_or_default();
    for (ci, code) in Code::all().into_iter().enumerate() {
        if !only.is_empty() && !only.split(',').any(|o| o == code.name()) {
            continue;
        }
        let (n, k) = (code.n(), code.k());
        let rate = k as f64 / n as f64;
        let rate_db = 10.0 * rate.log10();
        let na = design::normal_approx_db(n, k, 0.01);
        let lim = design::bi_awgn_limit_db(rate);
        let pts = sweep(code, Decoder::ALGORITHM, step, max_frames, 1000 + 100 * ci as u64);
        out += &format!(
            "\n#### {} (n = {n}, k = {k}, rate {rate:.3})\n\n\
             | Es/N0 BPSK (dB) | Eb/N0 (dB) | Es/N0 QPSK (dB) | frames | errors | FER | undetected | mean iter |\n\
             |---:|---:|---:|---:|---:|---:|---:|---:|\n",
            code.name()
        );
        for p in &pts {
            out += &format!(
                "| {:.2} | {:.2} | {:.2} | {} | {} | {:.2e} | {} | {:.1} |\n",
                p.db,
                p.db - rate_db,
                p.db + q,
                p.frames,
                p.errors,
                p.fer(),
                p.undetected,
                p.iters as f64 / p.frames as f64
            );
        }
        summary += &match crossing(&pts, 0.01) {
            Some(t) => format!(
                "| {} | {n} | {k} | {t:.2} | {:.2} | {:.2} | {na:.2} | {:.2} | {lim:.2} | {:.2} |\n",
                code.name(),
                t - rate_db,
                t + q,
                t - na,
                t - lim
            ),
            None => format!("| {} | {n} | {k} | n/a | | | {na:.2} | | {lim:.2} | |\n", code.name()),
        };
    }
    let text = format!("### Summary\n\n{summary}\n### FER curves\n{out}");
    match std::env::var("ION_FEC_RESULTS") {
        Ok(p) => std::fs::write(p, &text).unwrap(),
        Err(_) => println!("{text}"),
    }
}

/// Single-thread decode timing: mean at an operating point (default: the
/// normal-approximation 1% point + 1 dB) and worst case (iteration cap on
/// undecodable input).
/// Run: `cargo test -p ion --release --test fec decode_speed -- --ignored --nocapture`
#[test]
#[ignore]
fn decode_speed() {
    let mut rng = design::Rng::new(9);
    let mut noise = NoiseGen::new(9);
    let mut dec = Decoder::new();
    println!(
        "| code | Es/N0 (dB) | mean iter | mean decode (ms) | info kbit/s | worst case (ms, {} iter) |",
        Decoder::MAX_ITER
    );
    println!("|---|---:|---:|---:|---:|---:|");
    for code in Code::all() {
        let db = env_or(
            &format!("ION_FEC_OP_{}", code.name()),
            moderate_db(code.n(), code.k(), 1.0),
        );
        let frames = 300;
        let inputs: Vec<Vec<f32>> = (0..frames)
            .map(|_| {
                let info = rand_bits(&mut rng, code.k());
                bpsk_awgn(&code.encode(&info), db, &mut noise)
            })
            .collect();
        let mut it = 0;
        let t = std::time::Instant::now();
        for l in &inputs {
            std::hint::black_box(code.decode(&mut dec, l));
            it += dec.iterations();
        }
        let mean = t.elapsed().as_secs_f64() / frames as f64;
        let bad: Vec<Vec<f32>> = (0..20)
            .map(|_| {
                let info = rand_bits(&mut rng, code.k());
                bpsk_awgn(&code.encode(&info), -15.0, &mut noise)
            })
            .collect();
        let t = std::time::Instant::now();
        for l in &bad {
            std::hint::black_box(code.decode(&mut dec, l));
        }
        let worst = t.elapsed().as_secs_f64() / bad.len() as f64;
        println!(
            "| {} | {db:.2} | {:.1} | {:.3} | {:.0} | {:.3} |",
            code.name(),
            it as f64 / frames as f64,
            mean * 1e3,
            code.k() as f64 / mean / 1e3,
            worst * 1e3
        );
    }
}

/// Undetected errors (decoder converged to a wrong codeword) near each
/// code's 1% FER point, with the base-column support of the first few
/// error patterns. This is the check PEXIT cannot do: a cluster of
/// undetected errors means low-weight codewords.
/// Run: `cargo test -p ion --release --test fec undetected_errors -- --ignored --nocapture`
#[test]
#[ignore]
fn undetected_errors() {
    let frames = env_or("ION_FEC_FRAMES", 20_000);
    let only = std::env::var("ION_FEC_ONLY").unwrap_or_default();
    for (ci, code) in Code::all().into_iter().enumerate() {
        if !only.is_empty() && !only.split(',').any(|o| o == code.name()) {
            continue;
        }
        let db = env_or(
            &format!("ION_FEC_OP_{}", code.name()),
            moderate_db(code.n(), code.k(), 0.8),
        );
        let p = sim(code, db, Decoder::ALGORITHM, frames, 400, 500 + ci as u64);
        println!(
            "RESULT {} at {db:.2} dB: {} frames, {} errors, {} undetected",
            code.name(),
            p.frames,
            p.errors,
            p.undetected
        );
    }
    // Supports of a few undetected patterns at a lower SNR (more of them).
    let mut rng = design::Rng::new(42);
    let mut noise = NoiseGen::new(42);
    let mut dec = Decoder::new();
    let z = fec::Z;
    // Short code supports.
    for _ in 0..3 {
        let db = moderate_db(fec::n_short(), fec::K_SHORT, 0.3);
        for _ in 0..5000 {
            let info = rand_bits(&mut rng, fec::K_SHORT);
            let llr = bpsk_awgn(&fec::encode_short(&info), db, &mut noise);
            if let Some(b) = dec.decode_short(&llr).filter(|b| *b != info) {
                let d: Vec<u8> = b.iter().zip(&info).map(|(a, c)| a ^ c).collect();
                let x = fec::encode_short_mother(&d);
                let zs = fec::Z_SHORT;
                let cols: Vec<(usize, usize)> = (0..x.len() / zs)
                    .map(|c| (c, x[c * zs..(c + 1) * zs].iter().map(|&v| v as usize).sum()))
                    .filter(|&(_, w)| w > 0)
                    .collect();
                let sent: usize = x[2 * zs..].iter().map(|&v| v as usize).sum();
                println!("short at {db:.2} dB: sent weight {sent}, (column, weight) {cols:?}");
                break;
            }
        }
    }
    for r in Rate::ALL {
        let db = moderate_db(r.n(), fec::K, 0.3);
        let mut found = 0;
        for _ in 0..5000 {
            let info = rand_bits(&mut rng, fec::K);
            let llr = bpsk_awgn(&fec::encode(r, &info), db, &mut noise);
            if let Some(b) = dec.decode(r, &llr).filter(|b| *b != info) {
                let d: Vec<u8> = b.iter().zip(&info).map(|(a, c)| a ^ c).collect();
                let x = fec::encode_mother(&d);
                let tx: usize = fec::transmitted_positions(r).iter().map(|&p| x[p] as usize).sum();
                let cols: Vec<(usize, usize)> = (0..fec::N_FULL / z)
                    .map(|c| (c, x[c * z..(c + 1) * z].iter().map(|&v| v as usize).sum()))
                    .filter(|&(_, w)| w > 0)
                    .collect();
                println!("{r:?} at {db:.2} dB: sent weight {tx}, (column, weight) {cols:?}");
                found += 1;
                if found >= 3 {
                    break;
                }
            }
        }
    }
}

/// Gap to the normal approximation at prefixes between the ladder rates
/// (whole extension blocks), to see how smooth the family is for HARQ.
/// Run: `cargo test -p ion --release --test fec prefix_sweep -- --ignored --nocapture`
#[test]
#[ignore]
fn prefix_sweep() {
    let frames = env_or("ION_FEC_FRAMES", 5000);
    let lo: usize = env_or("ION_FEC_EXT_LO", 1);
    let hi: usize = env_or("ION_FEC_EXT_HI", 46);
    let step: usize = env_or("ION_FEC_EXT_STEP", 1);
    println!("| ext blocks | n | rate | 1% FER Es/N0 (dB) | normal approx. (dB) | gap (dB) |");
    println!("|---:|---:|---:|---:|---:|---:|");
    for e in (lo..=hi).step_by(step) {
        let n = (14 + 4 + e) * fec::Z;
        let code = Code::Prefix(n);
        let na = design::normal_approx_db(n, fec::K, 0.01);
        let pts = sweep(code, Decoder::ALGORITHM, 0.2, frames, 3000 + e as u64);
        match crossing(&pts, 0.01) {
            Some(t) => println!(
                "| {e} | {n} | {:.3} | {t:.2} | {na:.2} | {:.2} |",
                fec::K as f64 / n as f64,
                t - na
            ),
            None => println!("| {e} | {n} | | n/a | {na:.2} | |"),
        }
    }
}
