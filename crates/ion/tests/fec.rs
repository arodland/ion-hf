#[test]
fn encode_satisfies_all_checks() {
    let mut rng = design::Rng::new(1);
    for _ in 0..20 {
        let info = rand_bits(&mut rng, fec::K);
        let x = fec::encode_mother(&info);
        assert_eq!(x.len(), fec::N_FULL);
        assert_eq!(&x[..fec::K], &info[..], "systematic");
        assert!(fec::checks_satisfied(&x));
        // A single flipped sent bit breaks some check.
        let mut y = x.clone();
        let p = fec::transmission_order()[rng.below(fec::N_MOTHER)];
        y[p] ^= 1;
        assert!(!fec::checks_satisfied(&y));
        let s = fec::encode_short_mother(&info[..fec::K_SHORT]);
        assert!(fec::checks_satisfied_short(&s));
    }
    // All-zero info gives the all-zero codeword (linearity).
    assert!(fec::encode_mother(&[0; fec::K]).iter().all(|&b| b == 0));
}

#[test]
fn rate_compatible_subsets() {
    let mut rng = design::Rng::new(2);
    let order = fec::transmission_order();
    assert_eq!(order.len(), fec::N_MOTHER);
    for _ in 0..5 {
        let info = rand_bits(&mut rng, fec::K);
        let x = fec::encode_mother(&info);
        let mother_tx: Vec<u8> = order.iter().map(|&p| x[p]).collect();
        for r in Rate::ALL {
            let c = fec::encode(r, &info);
            assert_eq!(c.len(), r.n());
            let pos = fec::transmitted_positions(r);
            assert_eq!(pos, &order[..r.n()]);
            let sub: Vec<u8> = pos.iter().map(|&p| x[p]).collect();
            assert_eq!(c, sub, "{r:?}");
            assert_eq!(&c[..], &mother_tx[..r.n()]);
        }
    }
    // Lower rates extend higher ones.
    for w in Rate::ALL.windows(2) {
        let (lo, hi) = (w[0], w[1]);
        assert!(lo.n() > hi.n());
        assert_eq!(
            &fec::transmitted_positions(lo)[..hi.n()],
            fec::transmitted_positions(hi)
        );
    }
}

