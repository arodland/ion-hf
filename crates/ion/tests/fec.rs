#[test]
fn clean_round_trip_all_rates() {
    let mut rng = design::Rng::new(3);
    for r in Rate::ALL {
        for _ in 0..3 {
            let info = rand_bits(&mut rng, fec::K);
            let c = fec::encode(r, &info);
            assert_eq!(fec::decode(r, &clean_llrs(&c)), Some(info), "{r:?}");
        }
    }
    let info = rand_bits(&mut rng, fec::K_SHORT);
    let c = fec::encode_short(&info);
    assert_eq!(c.len(), fec::n_short());
    assert_eq!(fec::decode_short(&clean_llrs(&c)), Some(info));
}

#[test]
fn awgn_moderate_snr_decodes() {
    let mut rng = design::Rng::new(4);
    let mut noise = NoiseGen::new(4);
    for r in Rate::ALL {
        let db = moderate_db(r.n(), fec::K, 1.5);
        let mut ok = 0;
        for _ in 0..20 {
            let info = rand_bits(&mut rng, fec::K);
            let llr = bpsk_awgn(&fec::encode(r, &info), db, &mut noise);
            ok += (fec::decode(r, &llr).as_deref() == Some(&info[..])) as usize;
        }
        assert!(ok >= 19, "{r:?} at {db:.2} dB: {ok}/20");
    }
    let db = moderate_db(fec::n_short(), fec::K_SHORT, 1.5);
    let mut ok = 0;
    for _ in 0..20 {
        let info = rand_bits(&mut rng, fec::K_SHORT);
        let llr = bpsk_awgn(&fec::encode_short(&info), db, &mut noise);
        ok += (fec::decode_short(&llr).as_deref() == Some(&info[..])) as usize;
    }
    assert!(ok >= 19, "short at {db:.2} dB: {ok}/20");
}

#[test]
fn very_low_snr_gives_none() {
    let mut rng = design::Rng::new(5);
    let mut noise = NoiseGen::new(5);
    for r in Rate::ALL {
        for _ in 0..3 {
            let info = rand_bits(&mut rng, fec::K);
            let llr = bpsk_awgn(&fec::encode(r, &info), -15.0, &mut noise);
            assert_eq!(fec::decode(r, &llr), None, "{r:?}");
        }
    }
    let info = rand_bits(&mut rng, fec::K_SHORT);
    let llr = bpsk_awgn(&fec::encode_short(&info), -15.0, &mut noise);
    assert_eq!(fec::decode_short(&llr), None);
    // Garbage input must not panic either; all-erasure input is not a
    // codeword even though the all-zero word satisfies every check.
    let junk = vec![f32::NAN; Rate::R1_2.n()];
    assert_eq!(fec::decode(Rate::R1_2, &junk), None);
    assert_eq!(fec::decode(Rate::R5_6, &vec![0.0; Rate::R5_6.n()]), None);
    assert_eq!(fec::decode_short(&vec![0.0; fec::n_short()]), None);
    let inf = vec![f32::INFINITY; Rate::R3_4.n()];
    let _ = fec::decode(Rate::R3_4, &inf);
}

#[test]
fn erasures_at_punctured_positions() {
    let mut rng = design::Rng::new(6);
    let mut noise = NoiseGen::new(6);
    let mut dec = Decoder::new();
    // Rate 1/2 sent, decoded as rate 1/3 with the unsent tail erased.
    let db = moderate_db(Rate::R1_2.n(), fec::K, 1.5);
    for _ in 0..10 {
        let info = rand_bits(&mut rng, fec::K);
        let mut llr = bpsk_awgn(&fec::encode(Rate::R1_3, &info), db, &mut noise);
        llr[Rate::R1_2.n()..].iter_mut().for_each(|l| *l = 0.0);
        assert_eq!(dec.decode(Rate::R1_3, &llr).as_ref(), Some(&info));
        // HARQ entry point: any prefix length.
        assert_eq!(dec.decode_prefix(&llr[..Rate::R1_2.n() + 77]).as_ref(), Some(&info));
    }
    // Rate 1/3 with 20% of the bits erased at random, mild noise.
    for _ in 0..10 {
        let info = rand_bits(&mut rng, fec::K);
        let mut llr = bpsk_awgn(&fec::encode(Rate::R1_3, &info), 0.0, &mut noise);
        for l in llr.iter_mut() {
            if rng.below(5) == 0 {
                *l = 0.0;
            }
        }
        assert_eq!(dec.decode(Rate::R1_3, &llr).as_ref(), Some(&info));
    }
    // The full rate-1/4 mother via decode_prefix.
    let info = rand_bits(&mut rng, fec::K);
    let x = fec::encode_mother(&info);
    let tx: Vec<u8> = fec::transmission_order().iter().map(|&p| x[p]).collect();
    let llr = bpsk_awgn(&tx, moderate_db(fec::N_MOTHER, fec::K, 1.5), &mut noise);
    assert_eq!(dec.decode_prefix(&llr), Some(info));
}

